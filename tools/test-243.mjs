import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const c=JSON.parse(readFileSync(new URL('../shared/data/site.json',import.meta.url)));
const {checkedFeatureCenters,centerEvents,centerRouteKind,centerSportResults,centerHref,centerEventHref}=await import('../shared/js/feature-centers-data.js');
const data=checkedFeatureCenters(c);
assert.deepEqual(Object.keys(data).sort(),['community','education','exams','sports']);
assert.equal(data.education.programs.length,2);
assert.equal(centerSportResults(c).length,6);
assert.equal(centerSportResults(c,'Atlétika').length,1);
assert.equal(centerSportResults(c,'nincs-ilyen-sport').length,0);
assert.equal(centerEvents(c,'exams',{category:'exam'}).length,24);
assert.equal(centerEvents(c,'community',{category:'community'}).length,11);
assert.ok(centerEvents(c,'community',{query:'Csanádi-nap'}).length>=1);
assert.equal(centerEvents(c,'exams',{category:'holiday'}).length,3);
assert.ok(centerEvents(c,'exams',{query:'vizsga'}).length>5);
assert.equal(centerHref('education-exams'),'#/oldal/education-exams');
assert.equal(centerEventHref({id:'sportnap'}),'#/oldal/news-calendar/esemeny/sportnap');
assert.equal(centerRouteKind('education-programs'),'education');
assert.equal(centerRouteKind('sports-facilities'),'sports');
assert.equal(centerRouteKind('education-years'),'exams');
assert.equal(centerRouteKind('news-community'),'community');
assert.equal(centerRouteKind('information-documents'),null);
const wrong=structuredClone(c);wrong.featureCenters.sports.topics[0].mediaId='nem-letezo-kep';
assert.throws(()=>checkedFeatureCenters(wrong),/sportág-bemutató/);
const wrongLink=structuredClone(c);wrongLink.featureCenters.education.programs[0].pageId='bad-page';
assert.throws(()=>checkedFeatureCenters(wrongLink),/képzési kártya/);
const double=structuredClone(c);double.featureCenters.education.programs[1].id=double.featureCenters.education.programs[0].id;
assert.throws(()=>checkedFeatureCenters(double),/képzési kártya/);
assert.equal(c.publicNews.length,80);
assert.equal(c.publicNews.filter(n=>n.tags.includes('demo')).length,74);
assert.equal(c.home.carousel.panels.filter(x=>x.enabled).length,3);
assert.equal(c.home.carousel.autoplayMs,30000);
assert.match(readFileSync(new URL('../desktop/calendar.js',import.meta.url),'utf8'), /let mode="month"/);
assert.match(readFileSync(new URL('../mobile/calendar.js',import.meta.url),'utf8'), /let mode="month"/);
